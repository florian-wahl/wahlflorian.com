import React from "react";
import Head from "next/head";
import { useRouter } from "next/router";
import Navbar from "./Navbar";
import Footer from "./Footer";

const SITE_URL = "https://wahlflorian.com";

interface MetaProps {
    title?: string;
    description?: string;
    image?: string;
    type?: string;
    date?: string;
}

interface ContainerBlockProps {
    children: React.ReactNode;
    customMeta?: MetaProps;
}

const ContainerBlock: React.FC<ContainerBlockProps> = ({ children, customMeta = {} }) => {
    const router = useRouter();

    const meta: MetaProps = {
        title: "Florian Wahl - Product Leader & Fintech Strategist",
        description: `Florian Wahl is a product leader specializing in fintech infrastructure: open banking, payments, and data access. A decade across consulting, product management, and product strategy.`,
        image: "/og/default.png",
        type: "website",
        ...customMeta,
    };

    // OG/Twitter need absolute URLs. Share cards live under /og/ and are
    // generated at 1200x630 PNG by tools/og-cards.js.
    const imageUrl = meta.image?.startsWith("/") ? `${SITE_URL}${meta.image}` : meta.image;
    const isShareCard = !!meta.image?.startsWith("/og/");

    return (
        <div>
            <Head>
                <title>{meta.title}</title>
                {/* Icon set generated by `node tools/favicon.js` — re-run it after
                    any change to `--ink` or the dark `--accent`. The .ico carries
                    16/32/48 for legacy chrome; the SVG serves everything modern. */}
                <link rel="icon" href="/favicon.ico" sizes="32x32" />
                <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
                <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
                <link rel="manifest" href="/site.webmanifest" />
                {/* Mobile browser chrome tracks the `--canvas` token per scheme. The
                    keys are required: next/head dedupes meta by `name`, so without
                    them the two scheme variants collide and only the last survives. */}
                <meta key="theme-light" name="theme-color" content="#F5F6F8" media="(prefers-color-scheme: light)" />
                <meta key="theme-dark" name="theme-color" content="#101418" media="(prefers-color-scheme: dark)" />
                <meta name="robots" content="follow, index" />
                <meta content={meta.description} name="description" />
                <meta name="keywords" content="Florian Wahl, Product Leader, Product Strategy, Fintech, Digital Transformation, Akoya, Open Finance, Payments, API Development" />
                <meta name="author" content="Florian Wahl" />
                <meta name="news_keywords" content="Florian Wahl, Fintech, Product Strategy" />
                <meta name="revisit-after" content="7 days" />
                <meta name="rating" content="General" />
                <meta name="copyright" content="Florian Wahl" />
                <meta
                    property="og:url"
                    content={`${SITE_URL}${router.asPath}`}
                />
                <link
                    rel="canonical"
                    href={`${SITE_URL}${router.asPath}`}
                />
                <meta property="og:type" content={meta.type} />
                <meta property="og:site_name" content="Florian Wahl" />
                <meta property="og:description" content={meta.description} />
                <meta property="og:title" content={meta.title} />
                <meta property="og:image" content={imageUrl} />
                {isShareCard && (
                    <>
                        <meta property="og:image:width" content="1200" />
                        <meta property="og:image:height" content="630" />
                        <meta property="og:image:type" content="image/png" />
                    </>
                )}
                <meta property="og:image:alt" content={meta.title} />
                <meta name="twitter:card" content="summary_large_image" />
                <meta name="twitter:site" content="@flwahl" />
                <meta name="twitter:title" content={meta.title} />
                <meta name="twitter:description" content={meta.description} />
                <meta name="twitter:image" content={imageUrl} />
                <meta name="twitter:image:alt" content={meta.title} />
                {meta.date && (
                    <meta property="article:published_time" content={meta.date} />
                )}
                <script
                    type="application/ld+json"
                    dangerouslySetInnerHTML={{
                        __html: JSON.stringify({
                            "@context": "https://schema.org",
                            "@type": "Person",
                            name: "Florian Wahl",
                            jobTitle: "Product Leader",
                            description: meta.description,
                            // A Person's image is a photo of the person, not the
                            // page's share card.
                            image: `${SITE_URL}/headshot.webp`,
                            url: `${SITE_URL}${router.asPath}`,
                            sameAs: [
                                "https://www.linkedin.com/in/wahlflorian/",
                                "https://twitter.com/flwahl",
                                "https://medium.com/@flwahl"
                            ],
                            // No worksFor: the current employer is in stealth and
                            // can't be named. Better absent than stale.
                            alumniOf: [
                                { "@type": "Organization", name: "Akoya", url: "https://akoya.com" },
                                { "@type": "Organization", name: "Capgemini" }
                            ],
                            knowsAbout: [
                                "Product Strategy",
                                "Fintech",
                                "Digital Transformation",
                                "Open Finance",
                                "Payments",
                                "Product Management"
                            ]
                        })
                    }}
                />
                {meta.type === "article" && (
                    <script
                        type="application/ld+json"
                        dangerouslySetInnerHTML={{
                            __html: JSON.stringify({
                                "@context": "https://schema.org",
                                "@type": "BlogPosting",
                                headline: meta.title,
                                description: meta.description,
                                datePublished: meta.date,
                                image: imageUrl,
                                author: {
                                    "@type": "Person",
                                    name: "Florian Wahl",
                                    url: SITE_URL,
                                },
                                publisher: {
                                    "@type": "Person",
                                    name: "Florian Wahl",
                                    url: SITE_URL,
                                },
                                url: `${SITE_URL}${router.asPath}`,
                            })
                        }}
                    />
                )}
                <script
                    type="application/ld+json"
                    dangerouslySetInnerHTML={{
                        __html: JSON.stringify({
                            "@context": "https://schema.org",
                            "@type": "Blog",
                            url: `${SITE_URL}/articles`,
                            name: "Florian Wahl's Articles",
                            description: "Articles and insights about Product Strategy, Fintech, and Digital Transformation by Florian Wahl",
                            author: {
                                "@type": "Person",
                                name: "Florian Wahl"
                            }
                        })
                    }}
                />
            </Head>
            {/* Flex column so the footer sits at the bottom on short pages
                (404, contact) instead of floating mid-viewport. */}
            <main className="flex min-h-screen w-full flex-col bg-canvas">
                <Navbar />
                <div className="flex-1">{children}</div>
                <Footer />
            </main>
        </div>
    );
};

export default ContainerBlock; 
